const catalogs: Record<AppLocale, Catalog> = { en, es };

export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

export type MessageValues = Readonly<Record<string, number | string>>;

// Numbers in `values` are formatted for the locale; `count` also picks the
// plural form.
export function translate(
  locale: AppLocale,
  key: MessageKey,
  values: MessageValues = {},
): string {
  const entry: string | PluralMessage = catalogs[locale][key];
  const message =
    typeof entry === 'string' ? entry : (values.count === 1 ? entry.one : entry.other);

  return message.replace(/\{(\w+)\}/g, (placeholder: string, name: string) => {
    const value = values[name];
    if (value === undefined) return placeholder;
    return typeof value === 'number' ? formatNumber(locale, value) : value;
  });
}
